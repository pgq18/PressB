"""Cartesian color routes that make monotone progress toward the target XY."""
from __future__ import annotations

from copy import deepcopy
import hashlib
import json

import numpy as np
from scipy.spatial.transform import Rotation, Slerp

COLORS = ('red', 'yellow', 'blue')
MODE = 'target_relative_v2'
STYLES = dict(red='direct', yellow='lift_while_advancing', blue='overhead_then_down')


def quintic(u):
    u = np.clip(u, 0., 1.)
    return u*u*u*(10+u*(-15+6*u))


def targetward_metrics(xyz, start, end):
    """Measure horizontal detours/backtracking in metres, independent of height."""
    xyz, start, end = np.asarray(xyz), np.asarray(start), np.asarray(end)
    delta = end[:2]-start[:2]
    length = np.linalg.norm(delta)
    offset = xyz[:, :2]-start[:2]
    if length < 1e-8:
        lateral = np.linalg.norm(offset, axis=1)
        along = np.zeros(len(xyz))
    else:
        along = offset @ (delta/length)
        lateral = np.linalg.norm(offset-along[:, None]*(delta/length), axis=1)
    return dict(max_lateral_error_m=float(lateral.max()),
                max_backward_step_m=float(np.maximum(-np.diff(along), 0.).max(initial=0.)),
                max_overshoot_m=float(max(0., -along.min(), along.max()-length)))


class TargetRelativeTemplates:
    """Solve/cache the actual 30 Hz prefix used by screening and execution.

    All routes finish at the original near-contact pose. The press itself is
    generated by motion.plan_press. XY stays on the initial-to-target segment;
    only the vertical profile and rate of forward progress vary with color.
    """

    def __init__(self, kin, cfg):
        raw = cfg['motion_templates']
        allowed = {'mode', 'transit_duration_s', 'mid_lift_m', 'overhead_z_m',
                   'min_transit_separation_m'}
        if set(raw)-allowed:
            raise ValueError(f'Unknown target-relative options: {sorted(set(raw)-allowed)}')
        self.kin = kin
        self.initial = np.asarray(cfg['initial_joint_positions_rad'], dtype=float)
        self.fps = int(cfg.get('fps', 30))
        duration = float(raw.get('transit_duration_s', 3.6))
        lift = float(raw.get('mid_lift_m', .06))
        overhead = float(raw.get('overhead_z_m', .18))
        separation = float(raw.get('min_transit_separation_m', .03))
        if (not np.isfinite([duration, lift, overhead, separation]).all()
                or duration < 2.7 or lift <= 0 or overhead <= .12 or separation < 0):
            raise ValueError('Invalid target-relative height, timing or separation')
        if self.fps <= 0 or any(abs(duration*f*self.fps-round(duration*f*self.fps)) > 1e-8
                                for f in (1., .5, 2/3)):
            raise ValueError('Target-relative phase boundaries must lie on the control clock')
        self.options = dict(mode=MODE, transit_duration_s=duration, mid_lift_m=lift,
                            overhead_z_m=overhead, min_transit_separation_m=separation)
        signature_data = dict(options=self.options, fps=self.fps, initial=self.initial.tolist())
        self.signature = hashlib.sha256(json.dumps(signature_data, sort_keys=True).encode()).hexdigest()
        self._routes = {}

    def attach(self, approach, color):
        if color not in COLORS:
            raise ValueError('A color is required for target-relative motion')
        near = np.asarray(approach['near'], dtype=float)
        orientation = np.asarray(approach['orientation'], dtype=float)
        key = (color, tuple(near), tuple(orientation.ravel()))
        if key not in self._routes:
            self._routes[key] = self._build(near, orientation, color)
        result = {key: value for key, value in approach.items()
                  if key not in ('transit_waypoints_rad', 'transit_path', 'motion_template')}
        result.update(deepcopy(self._routes[key]))
        return result

    def _build(self, near, orientation, color):
        pose = self.kin.fk(self.initial)
        start = pose[:3, 3]
        height = max(start[2], near[2])
        if color == 'red':
            knots, fractions = np.array([start, near]), np.array([0., 1.])
        elif color == 'yellow':
            middle = start+.4*(near-start)
            middle[2] = height+self.options['mid_lift_m']
            knots, fractions = np.array([start, middle, near]), np.array([0., .5, 1.])
        else:
            above = near.copy()
            above[2] = max(height, self.options['overhead_z_m'])
            knots, fractions = np.array([start, above, near]), np.array([0., 2/3, 1.])

        # Follow radial yaw at every Cartesian point. Interpolating world-frame
        # yaw independently of XYZ can demand impossible lateral wrist poses.
        yaw0, yaw1 = (np.arctan2(p[1], p[0]) for p in (start, near))
        local = Slerp([0., 1.], Rotation.from_matrix([
            Rotation.from_euler('z', -yaw0).as_matrix() @ pose[:3, :3],
            Rotation.from_euler('z', -yaw1).as_matrix() @ orientation]))
        duration = self.options['transit_duration_s']
        times = np.arange(round(duration*self.fps)+1)/self.fps
        q = self.initial.copy()
        joints, points = [q], [start]
        for seconds in times[1:]:
            u = seconds/duration
            leg = min(np.searchsorted(fractions, u, side='right')-1, len(fractions)-2)
            blend = quintic((u-fractions[leg])/(fractions[leg+1]-fractions[leg]))
            xyz = knots[leg]+blend*(knots[leg+1]-knots[leg])
            rotation = (Rotation.from_euler('z', np.arctan2(xyz[1], xyz[0])).as_matrix()
                        @ local([quintic(u)]).as_matrix()[0])
            q = self.kin.solve(xyz, q, rotation)
            joints.append(q)
            points.append(xyz)
        joints = np.asarray(joints)
        if np.any(np.max(np.abs(np.diff(joints, axis=0)), axis=0)*self.fps > self.kin.velocity_limits):
            raise ValueError('Target-relative Cartesian path exceeds joint velocity limits')
        dense_times = np.linspace(0., duration, 4*(len(times)-1)+1)
        dense = np.column_stack([np.interp(dense_times, times, joints[:, j]) for j in range(6)])
        actual = np.array([self.kin.fk(row)[:3, 3] for row in dense])
        direction = targetward_metrics(actual, start, near)
        if (direction['max_lateral_error_m'] > .001 or direction['max_backward_step_m'] > .0005
                or direction['max_overshoot_m'] > .001):
            raise ValueError(f'Target-relative path deviates from forward Cartesian corridor: {direction}')
        return dict(transit_path=dict(time_s=times.tolist(), joints_rad=joints.tolist(),
                                      tip_xyz_m=np.asarray(points).tolist()),
                    motion_template=dict(mode=MODE, color=color, path_style=STYLES[color],
                        knots_base_m=knots.tolist(), time_fractions=fractions.tolist(),
                        transit_duration_s=duration, config_signature=self.signature,
                        targetward_check=direction))

    def validate(self, approach, color):
        expected = self.attach(approach, color)
        if (approach.get('transit_waypoints_rad')
                or approach.get('motion_template') != expected['motion_template']
                or approach.get('transit_path') != expected['transit_path']):
            raise ValueError('Stale or mismatched target-relative motion template in layout')

    def diversity(self, initial_q, approaches):
        if not np.allclose(initial_q, self.initial, rtol=0., atol=1e-10):
            raise ValueError('Target-relative routes belong to a different initial pose')
        traces = {}
        for color in COLORS:
            self.validate(approaches[color], color)
            path = approaches[color]['transit_path']
            times, joints = np.asarray(path['time_s']), np.asarray(path['joints_rad'])
            times_new = np.linspace(0., times[-1], 121)
            sampled = np.column_stack([np.interp(times_new, times, joints[:, j]) for j in range(6)])
            traces[color] = np.array([self.kin.fk(row)[:3, 3] for row in sampled])
        distances = {f'{a}_{b}': float(np.linalg.norm(traces[a]-traces[b], axis=1).mean())
                     for i, a in enumerate(COLORS) for b in COLORS[i+1:]}
        threshold = self.options['min_transit_separation_m']
        return dict(accepted=min(distances.values()) >= threshold, mode=MODE,
                    metric='mean synchronous FK tip distance from initial pose to near-contact pose; 121 points; metres',
                    pairwise_mean_tip_distance_m=distances, min_transit_separation_m=threshold)
