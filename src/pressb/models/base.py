"""Frozen model boundary. No simulator or reward logic belongs in this layer."""
from typing import Protocol, runtime_checkable


@runtime_checkable
class ModelAdapter(Protocol):
    def describe(self) -> dict: ...
    def encode_batch(self, observations: list[dict], seeds: list[int]) -> list[tuple]: ...
    def decode_batch(self, contexts: list, initial_noises: list) -> list: ...
    def close(self) -> None: ...
